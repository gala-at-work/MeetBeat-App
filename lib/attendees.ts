function initialsOf(name: string): string {
  return name
    .split(' ')
    .filter(Boolean)
    .slice(0, 2)
    .map((part) => part[0]?.toUpperCase() ?? '')
    .join('');
}

function toPerson(seed: Seed, index: number): Person {
  const signals: Signals = {
    seeking: seed.seek,
    offering: seed.offer,
    skills: seed.sk,
    industries: seed.ind,
    interests: seed.int,
    stage: seed.st,
    ask: seed.ask,
    give: seed.give,
  };

  return {
    id: `p${String(index + 1).padStart(2, '0')}`,
    name: seed.n,
    headline: seed.h,
    role: seed.r,
    company: seed.c,
    location: seed.loc,
    bio: seed.bio,
    hook: seed.hook,
    signals,
  };
}

export const ATTENDEES: Person[] = SEEDS.map(toPerson);

const ATTENDEE_BY_ID = new Map(ATTENDEES.map((person) => [person.id, person]));

export function findAttendee(id: string): Person | undefined {
  return ATTENDEE_BY_ID.get(id);
}

export function initials(name: string): string {
  return initialsOf(name);
}

