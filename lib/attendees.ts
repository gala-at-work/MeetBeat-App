/**
 * Who is actually in a given room. Seeded events narrow the demo cohort by
 * industry focus; investors and advisors top up the smaller rooms because they
 * move between every event.
 */
export function cohortForEvent(event: EventInfo): Person[] {
  if (event.cohortIndustries.length === 0) {
    return ATTENDEES.slice(0, Math.max(1, event.cohortSize));
  }

  const focused = ATTENDEES.filter((person) =>
    person.signals.industries.some((industry) => event.cohortIndustries.includes(industry)),
  );
  const focusedIds = new Set(focused.map((person) => person.id));
  const connectors = ATTENDEES.filter(
    (person) =>
      !focusedIds.has(person.id) && (person.role === 'investor' || person.role === 'advisor'),
  );

  return [...focused, ...connectors].slice(0, Math.max(1, event.cohortSize));
}
